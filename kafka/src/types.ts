/**
 * types.ts
 *
 * Canonical TypeScript types for all Kafka events in the ShopSphere platform.
 *
 * VERSIONING POLICY
 * -----------------
 * - eventVersion follows MAJOR.MINOR.
 * - Bump MINOR for additive (backward-compatible) changes.
 * - Bump MAJOR for breaking changes; create a new consumer branch.
 *
 * PAYLOAD FIELDS
 * --------------
 * Fields marked ⚠️ PROVISIONAL are owned by the backend teammate.
 * Do not treat them as final until the backend teammate confirms
 * the actual PostgreSQL schema and API order-object structure.
 *
 * INTEGRATION CONTRACT
 * --------------------
 * This file is the agreed boundary between the Kafka module and the
 * Express backend. Any change to payload fields must be discussed and
 * version-bumped before both sides are updated.
 *
 * See kafka/src/contracts/event-contract.md for the human-readable contract
 * document to share with teammates.
 */

// ---------------------------------------------------------------------------
// Shared envelope — owned by the Kafka module
// ---------------------------------------------------------------------------

export interface EventEnvelope {
  /**
   * Unique identifier for this event instance.
   * Generated by the producer as a UUID v4.
   * Used as the idempotency key by consumers.
   */
  eventId: string;

  /**
   * Semantic version of the event schema.
   * Current: "1.0"
   */
  eventVersion: "1.0";

  /**
   * The name of the event. Used by consumers to route to the correct handler.
   */
  eventName: string;

  /**
   * ISO 8601 timestamp of when the order event *occurred* in the domain
   * (i.e. when the backend committed the order to the database),
   * NOT when the Kafka message was published.
   * Set by the caller of publishOrderPlaced(), sourced from the backend.
   */
  occurredAt: string;
}

