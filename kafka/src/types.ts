export interface OrderPlacedEvent extends EventEnvelope {
  eventName: "order_placed";
  payload: OrderPlacedPayload;
}

// ---------------------------------------------------------------------------
// Runtime payload validation
// ---------------------------------------------------------------------------

/**
 * Validates that a parsed object has the minimum required shape to be
 * treated as a valid OrderPlacedEvent.
 *
 * This is a structural guard only — it does not validate field values.
 * Returns a string describing the first problem found, or null if valid.
 */
export function validateOrderPlacedEvent(raw: unknown): string | null {
  if (typeof raw !== "object" || raw === null) {
    return "Event is not an object";
  }

  const e = raw as Record<string, unknown>;

  if (typeof e.eventId !== "string" || e.eventId.trim() === "") {
    return "Missing or empty eventId";
  }
  if (e.eventName !== "order_placed") {
    return `Unexpected eventName: ${String(e.eventName)}`;
  }
  if (typeof e.eventVersion !== "string") {
    return "Missing eventVersion";
  }
  if (typeof e.occurredAt !== "string" || e.occurredAt.trim() === "") {
    return "Missing or empty occurredAt";
  }
  if (typeof e.payload !== "object" || e.payload === null) {
    return "Missing or null payload";
  }

  const p = e.payload as Record<string, unknown>;

  if (typeof p.orderId !== "string" || p.orderId.trim() === "") {
    return "payload.orderId is missing or empty";
  }
  if (typeof p.customerId !== "string" || p.customerId.trim() === "") {
    return "payload.customerId is missing or empty";
  }
  if (typeof p.totalAmount !== "number") {
    return "payload.totalAmount is not a number";
  }
  if (typeof p.status !== "string" || p.status.trim() === "") {
    return "payload.status is missing or empty";
  }
  if (!Array.isArray(p.items)) {
    return "payload.items is not an array";
  }

  for (let i = 0; i < (p.items as unknown[]).length; i++) {
    const item = (p.items as unknown[])[i] as Record<string, unknown>;
    if (typeof item !== "object" || item === null) {
      return `payload.items[${i}] is not an object`;
    }
    if (typeof item.productId !== "string" || (item.productId as string).trim() === "") {
      return `payload.items[${i}].productId is missing or empty`;
    }
    if (typeof item.quantity !== "number" || (item.quantity as number) < 1) {
      return `payload.items[${i}].quantity must be a positive number`;
    }
    if (typeof item.unitPrice !== "number") {
      return `payload.items[${i}].unitPrice is not a number`;
    }
  }

  return null; // valid
}


