// Helper to format new products into typescript
function formatProduct(p) {
  return `  ${JSON.stringify(p, null, 2).replace(/"([^"]+)":/g, '$1:')}`;
}

const formattedNewProducts = newProducts.map(p => {
  // generate variants if empty
  const sizes = p.sizes || [];
  const colors = p.colors || [];
  const variants = [];
  sizes.forEach(s => {
    colors.forEach(c => {
      variants.push({
        id: "var-" + p.id + "-" + s.id + "-" + c.id,
        sku: p.sku + "-" + s.label + "-" + c.id.toUpperCase(),
        size: s.name,
        color: c.name,
        colorCode: c.code,
        price: p.price,
        stock: Math.max(1, Math.floor((p.stock || 20) / (sizes.length * colors.length || 1))),
        image: p.srcUrl
      });
    });
  });

  const fullProd = {
    ...p,
    variants
  };

  return JSON.stringify(fullProd, null, 2);
}).join(',\n');

